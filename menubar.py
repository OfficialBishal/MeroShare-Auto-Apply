"""macOS menu bar app for MeroShare Auto-Apply.

Lives in the system menu bar and exposes the app without forcing a
browser tab to stay open. Talks to the Flask backend over the
existing /api/* endpoints; spawns Flask on demand.

The menu surfaces:
  - status header (version + scheduler / next-run summary)
  - per-issue submenu, click an issue to open it on the dashboard
  - per-account submenu with apply-now and login-test shortcuts
  - background scheduler toggle + interval picker
  - preferences (share types, kitta, launch-at-login)
  - update channel: notification + click-to-download

This module is macOS-only because rumps wraps Cocoa's NSStatusItem.
Requirements gates the dep with `; sys_platform == "darwin"`.
"""
