    # ── HTTP plumbing ──────────────────────────────────────────────

    def _flask_alive(self) -> bool:
        try:
            r = requests.get(f"{BASE_URL}/api/health", timeout=2)
            return r.status_code in (200, 503)
        except requests.RequestException:
            return False

    def _api(self, path: str, method: str = "GET", **kwargs):
        try:
            resp = requests.request(method, f"{BASE_URL}{path}", timeout=8, **kwargs)
            if not resp.ok:
                return None
            if resp.text:
                return resp.json()
            return {}
        except (requests.RequestException, ValueError) as e:
            logger.debug("%s %s failed: %s", method, path, e)
            return None

    def _ensure_flask(self) -> bool:
        """Start Flask if not already running. Returns True when reachable."""
        if self._flask_alive():
            return True
        python = sys.executable
        app_py = BASE_DIR / "app.py"
        if not app_py.exists():
            _show_dialog(
                "App files missing",
                f"app.py not found at {app_py}.\nRe-install the app.",
            )
            return False
        try:
            self._flask_proc = subprocess.Popen(
                [python, str(app_py)],
                cwd=str(BASE_DIR),
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                start_new_session=True,
            )
        except OSError as e:
            _show_dialog("Could not start app", str(e))
            return False
        # Poll up to 10s for the bind. Cold first-imports on the
        # bundled venv can take a couple of seconds.
        for _ in range(20):
            if self._flask_alive():
                return True
            time.sleep(0.5)
        _show_dialog(
            "App did not start",
            f"Flask is not responding on port {PORT}. See ~/Library/Logs/"
            "MeroShare Auto-Apply/menubar.log.",
        )
        return False

    def _auto_start_flask(self) -> None:
        """Spawn Flask quietly at app launch.

        Same code path as `_ensure_flask` but without the
        modal-dialog-on-failure UX — auto-start should never block the
        user with a popup at login. If Flask doesn't come up, the
        status line in the menu (`Status: app stopped`) and the
        first user click on Open Dashboard surface the failure
        clearly enough.

        We also defer slightly so the menu bar item is fully wired up
        before the bundled-Python import overhead hits — keeps the
        click-the-icon-and-see-the-menu latency minimal.
        """
        # Slight delay: lets the menu bar render before we burn CPU
        # on the cold Python boot. Imperceptible to the user, but
        # avoids a "click-and-spinner" experience right after login.
        time.sleep(0.5)
        if self._flask_alive():
            return
        python = sys.executable
        app_py = BASE_DIR / "app.py"
        if not app_py.exists():
            logger.warning("auto-start: app.py not found at %s", app_py)
            return
        try:
            self._flask_proc = subprocess.Popen(
                [python, str(app_py)],
                cwd=str(BASE_DIR),
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                start_new_session=True,
            )
            logger.info("Auto-started Flask (pid=%s)", self._flask_proc.pid)
        except OSError as e:
            logger.warning("auto-start: subprocess.Popen failed: %s", e)
            return
        # Poll for readiness so the next status tick paints "ready"
        # rather than "stopped" — but cap at 15s so a wedged Flask
        # doesn't hold the thread indefinitely.
        for _ in range(30):
            if self._flask_alive():
                logger.info("Flask reached /api/health on auto-start")
                # Clear the launch-time "Starting…" title so the menu
                # bar returns to icon-only (the user's preference for
                # steady state). Setting `title=None` rather than ""
                # is the rumps-native way to drop the text.
                if ICON_PATH.exists():
                    try:
                        # Clear the launch-time "Starting…" title so
                        # the menu bar settles to icon-only.
                        self.title = None
                    except Exception as e:
                        logger.debug("Could not clear menubar title: %s", e)
                # Trigger an immediate refresh so the status header
                # flips from "starting…" without waiting for the 30s
                # tick.
                threading.Thread(target=self._refresh_all, daemon=True).start()
                # Note: an explicit "MeroShare Auto-Apply is running"
                # notification was tried here. macOS auto-attaches a
                # "Show" action button to notifications from
                # LSUIElement apps that osascript can't suppress, and
                # it doesn't do anything useful (no main window to
                # bring forward). The menu bar transition from
                # "Starting…" → icon-only is the better feedback
                # mechanism: always visible, no actionable junk.
                return
            time.sleep(0.5)
        logger.warning(
            "auto-start: Flask didn't reach /api/health within 15s; "
            "status will reflect 'stopped' until next user action.",
        )
        # Failure path: keep the "M" anchor visible. The menu's
        # status header will flag "Status: app stopped" on its next
        # tick so the user has actionable feedback.
        if ICON_PATH.exists():
            try:
                self.title = None
            except Exception as e:
                logger.debug("Could not clear menubar title: %s", e)
        # When Flask doesn't bind in time, the menu's status header
        # paints "Status: app stopped" on its next tick — that's the
        # surface the user sees. We deliberately do NOT toast a
        # notification here either (same Show-button issue).

    # ── Tick handlers ──────────────────────────────────────────────

    def _tick(self, _sender) -> None:
        # Sentinel: the GUI's "Stop everything" route writes a file
        # we delete and exit on. TTL guard: a sentinel from a past
        # crash that wasn't cleaned up shouldn't block forever.
        # 5 minutes is more than enough margin for the GUI -> menu
        # bar tick delay (max 30s) but recognizes a stale file when
        # it sees one.
        SENTINEL_TTL_S = 5 * 60
        try:
            stat = SHUTDOWN_SENTINEL.stat()
        except FileNotFoundError:
            stat = None
        except OSError as e:
            logger.debug("Sentinel stat failed: %s", e)
            stat = None
        if stat is not None:
            age = time.time() - stat.st_mtime
            try:
                SHUTDOWN_SENTINEL.unlink()
            except OSError as e:
                logger.debug("Sentinel unlink failed: %s", e)
            if age <= SENTINEL_TTL_S:
                logger.info("Shutdown sentinel observed; exiting menu bar.")
                rumps.quit_application()
                return
            logger.info(
                "Ignoring stale shutdown sentinel (%.0fs old > %ds TTL).",
                age, SENTINEL_TTL_S,
            )
        threading.Thread(target=self._refresh_all, daemon=True).start()

    def _update_tick(self, _sender) -> None:
        threading.Thread(target=self._check_updates, daemon=True).start()

    def _sentinel_check_tick(self, _sender) -> None:
        """Fast-poll the shutdown sentinel that the dashboard's
        Stop-everything path writes. Runs on the rumps event loop, so
        it doesn't suffer from Python's signal-handler deferral when
        the main thread is parked in the Cocoa runloop.

        The 30-second main `_tick` also checks the sentinel as a
        backstop; this faster timer just makes the user-facing
        latency match the click-to-disappear UX they expect.
        """
        SENTINEL_TTL_S = 5 * 60
        try:
            stat = SHUTDOWN_SENTINEL.stat()
        except FileNotFoundError:
            return
        except OSError:
            return
        age = time.time() - stat.st_mtime
        if age >= SENTINEL_TTL_S:
            return  # stale from a past crash, ignore
        try:
            SHUTDOWN_SENTINEL.unlink()
        except OSError:
            pass
        logger.info("Shutdown sentinel observed (fast tick); exiting menu bar.")
        if self._flask_proc and self._flask_proc.poll() is None:
            try:
                self._flask_proc.terminate()
            except OSError:
                pass
        rumps.quit_application()

    def _refresh_app_icon_image(self) -> None:
        """Explicitly set NSApp.applicationIconImage from the bundle's
        icon.icns so notifications and the Dock show the correct logo.

        The bundle layout we expect:
            …/MeroShare Auto-Apply.app/Contents/Resources/icon.icns
            …/MeroShare Auto-Apply.app/Contents/Resources/app/menubar.py
        So `BASE_DIR.parent / "icon.icns"` is the icon.

        No-op if the icon file isn't where we expect (dev mode running
        from source has no .icns; that's fine — the menu bar template
        PNG is its own thing). Failures are swallowed — a wrong icon
        is cosmetic, but a startup crash would be fatal.
        """
        try:
            bundle_icns = BASE_DIR.parent / "icon.icns"
            if not bundle_icns.exists():
                return
            from AppKit import NSApp, NSImage
            img = NSImage.alloc().initByReferencingFile_(str(bundle_icns))
            if img:
                NSApp.setApplicationIconImage_(img)
                logger.info("Registered bundle icon for notifications + Dock.")
        except Exception as e:
            logger.debug("Could not refresh app icon image: %s", e)

    def _drain_notifications(self, _sender) -> None:
        """Pull queued notifications from the cross-process JSONL queue
        and fire each as a native NSUserNotification.

        The Flask process can't fire these directly with the right icon
        (it's a subprocess detached from the .app bundle), so it appends
        to the queue and we — owning the bundle — drain. Failures are
        swallowed: a notification that doesn't fire is far better than
        a menu bar that crashes because Notification Center is acting
        up.
        """
        try:
            entries = notification_queue.drain()
        except Exception as e:
            logger.debug("Notification drain failed: %s", e)
            return
        for entry in entries:
            try:
                rumps.notification(
                    title=entry.get("title") or "MeroShare Auto-Apply",
                    subtitle="",
                    message=entry.get("message") or "",
                    sound=False,
                )
            except Exception as e:
                logger.debug("rumps.notification failed: %s", e)

    # ── State refresh ──────────────────────────────────────────────

    def _refresh_all(self) -> None:
        """Pull state from the Flask API and update the menu in place."""
        flask_alive = self._flask_alive()
        if not flask_alive:
            self._render_offline()
            self._was_offline = True
            return

        # Detect the offline → online transition. After _render_offline,
        # all four submenus carry the "(app stopped)" placeholder and
        # the cached states are zeroed. If the next /api response
        # happens to also be empty (e.g. /api/scheduler returns {}
        # because we hit it during a brief Flask cold-start window
        # where some endpoints aren't ready), the equality short-
        # circuits below would skip the repaint and leave the
        # placeholders stuck — exactly the bug the user reported.
        # Force a full repaint on the transition.
        was_offline = getattr(self, "_was_offline", True)
        self._was_offline = False

        # All four endpoints are local and cheap; fetch sequentially
        # to keep the rumps menu stable (avoid mutations from N
        # concurrent threads).
        new_scheduler = self._api("/api/scheduler") or {}
        new_accounts = self._api("/api/accounts") or []
        issues_resp = self._api("/api/issues") or {}
        # /api/issues returns {"issues": [...]} on the happy path, but a
        # cold-start Flask can briefly return {}. The `or []` here
        # handles both: missing key → None → [], and non-dict → bare
        # list. The previous form left `or []` only on the else
        # branch and let None leak through to _render_status_lines.
        if isinstance(issues_resp, dict):
            new_issues = issues_resp.get("issues") or []
        else:
            new_issues = issues_resp or []
        new_config = self._api("/api/config") or {}

        # Skip rebuilding submenus whose source data is byte-for-byte
        # identical to what we last rendered. Avoids menu flicker if
        # the user has the menu open during a tick. On the offline →
        # online transition, force a repaint regardless.
        sched_changed = was_offline or new_scheduler != self._scheduler_state
        accts_changed = was_offline or new_accounts != self._accounts_state
        issues_changed = was_offline or new_issues != self._issues_state
        config_changed = was_offline or new_config != self._config_state

        self._scheduler_state = new_scheduler
        self._accounts_state = new_accounts
        self._issues_state = new_issues
        self._config_state = new_config

        # Status lines are cheap; always re-render so "X minutes ago"
        # ticks forward.
        self._render_status_lines()
        if issues_changed:
            self._render_issues_submenu()
        if accts_changed:
            self._render_accounts_submenu()
        if sched_changed:
            self._render_scheduler_submenu()
        if config_changed or sched_changed:
            self._render_prefs_submenu()

    def _render_offline(self) -> None:
        self._status_line.title = "Status: starting…"
        self._next_run_line.title = "Scheduler: -"
        self._issue_count_line.title = "Open issues: -"
        # Only reset the submenus whose CONTENT depends on a live
        # Flask response: Open Issues (needs /api/issues) and Accounts
        # (needs /api/accounts). Scheduler and Preferences are
        # config-driven; their last-known state from /api/config or
        # the empty-state __init__ paint is more useful than a
        # "(app stopped)" placeholder that gets stuck if a subsequent
        # refresh's data happens to be byte-equal.
        # The status header above already conveys "Status: starting…"
        # so the user knows things are coming up — duplicating that
        # message inside every submenu is noise.
        self._reset_submenu(self._issues_menu, "(starting…)")
        self._reset_submenu(self._accounts_menu, "(starting…)")
        # Drop our cached state for the Flask-dependent submenus so
        # the next online tick rebuilds them from scratch (the equality
        # short-circuits in _refresh_all would otherwise compare
        # against stale state).
        self._issues_state = []
        self._accounts_state = []
        # The "Update Available" item title is sticky between
        # update-check ticks. If we previously detected an update and
        # then went offline, the title stays "Update Available: vX →"
        # until the next successful check. Reset to the neutral
        # title so a stale update prompt doesn't confuse the user.
        if self._update_info is None:
            self._update_item.title = "Check for Updates…"

    def _render_status_lines(self) -> None:
        sched = self._scheduler_state
        if sched.get("enabled"):
            interval = sched.get("interval_hours")
            last = sched.get("last_result") or "no runs yet"
            self._status_line.title = (
                f"Status: scheduler on, every {interval}h"
            )
            last_run = sched.get("last_run")
            next_run = sched.get("next_run")
            parts = []
            if last_run:
                parts.append(f"last run {_format_relative(last_run)}")
            if next_run:
                parts.append(f"next {_format_relative(next_run)}")
            if last and len(last) <= 80:
                parts.append(last)
            self._next_run_line.title = "  " + (" · ".join(parts) or "-")
        else:
            self._status_line.title = "Status: scheduler off"
            self._next_run_line.title = "  not scheduled"

        # Issue count read from the per-account response; sum unique
        # companyShareIds so a single issue applicable to N accounts
        # counts once.
        unique = {
            str(i.get("companyShareId") or i.get("id") or "")
            for i in self._issues_state if i
        } - {""}
        self._issue_count_line.title = f"Open issues: {len(unique)}"

    # ── Issues submenu ─────────────────────────────────────────────

    def _render_issues_submenu(self) -> None:
        self._reset_submenu(self._issues_menu)
        issues = self._issues_state or []
        if not issues:
            self._issues_menu.add(rumps.MenuItem("(no open issues)"))
            return
        # Dedupe by companyShareId so a multi-account workspace
        # doesn't repeat the same issue per account in the menu.
        seen: set[str] = set()
        rendered = 0
        for issue in issues:
            iid = str(issue.get("companyShareId") or issue.get("id") or "")
            if not iid or iid in seen:
                continue
            seen.add(iid)
            self._issues_menu.add(self._build_issue_menu_item(issue))
            rendered += 1
            if rendered >= MAX_ISSUES_IN_MENU:
                self._issues_menu.add(rumps.MenuItem(
                    f"… and {len(issues) - rendered} more",
                ))
                break

    def _build_issue_menu_item(self, issue: dict) -> rumps.MenuItem:
        # The /api/issues route normalizes raw MeroShare field names
        # into shorter ones (`company`, `shareType`) — the menubar
        # was previously reading the raw names and getting "?" for
        # everything. Try the normalized name first, then fall back
        # to the raw MeroShare name in case a future caller (e.g.
        # locally-cached records) supplies the unnormalized shape.
        company = (
            issue.get("company")
            or issue.get("companyName")
            or "?"
        )
        share_type = (
            issue.get("shareType")
            or issue.get("shareTypeName")
            or ""
        )
        # "?" share types are placeholders the API uses when it can't
        # classify; suppress them in the menu so the title stays clean.
        if share_type == "?":
            share_type = ""
        title = company if not share_type else f"{company} ({share_type})"
        item = rumps.MenuItem(title)

        # Per-account application chips. The /api/issues route returns
        # `applications` as a {account_id: {applied: bool, …}} dict.
        # Fall back to the older `accountChips` / `chips` shapes for
        # forward-compat.
        applications = issue.get("applications")
        if isinstance(applications, dict):
            total = len(applications)
            applied = sum(1 for a in applications.values()
                          if isinstance(a, dict) and a.get("applied"))
        else:
            chips = issue.get("accountChips") or issue.get("chips") or []
            applied = sum(1 for c in chips if c.get("state") == "applied")
            total = len(chips)
        if total:
            item.add(rumps.MenuItem(f"{applied}/{total} accounts applied"))

        iid = issue.get("id") or issue.get("companyShareId")

        def _open(_sender, _iid=iid):
            self._on_open_issue(_iid)

        item.add(rumps.MenuItem("Open on dashboard", callback=_open))
        return item

    # ── Accounts submenu ───────────────────────────────────────────

    def _render_accounts_submenu(self) -> None:
        self._reset_submenu(self._accounts_menu)
        accts = self._accounts_state or []
        if not accts:
            self._accounts_menu.add(
                rumps.MenuItem("(no accounts configured)", callback=self._on_open_settings),
            )
            return
        for a in accts[:MAX_ACCOUNTS_IN_MENU]:
            self._accounts_menu.add(self._build_account_menu_item(a))
        if len(accts) > MAX_ACCOUNTS_IN_MENU:
            self._accounts_menu.add(rumps.MenuItem(
                f"… and {len(accts) - MAX_ACCOUNTS_IN_MENU} more",
            ))
        self._accounts_menu.add(None)
        self._accounts_menu.add(rumps.MenuItem(
            "Manage accounts…", callback=self._on_open_settings,
        ))

    def _build_account_menu_item(self, acct: dict) -> rumps.MenuItem:
        name = acct.get("name", "?")
        item = rumps.MenuItem(name)
        dp = acct.get("dp_id", "?")
        boid = acct.get("username", "?")
        item.add(rumps.MenuItem(f"DP {dp} · BOID {boid}"))

        bank = acct.get("preferred_bank")
        if bank:
            item.add(rumps.MenuItem(f"Bank: {bank}"))

        aid = acct.get("id")

        def _test(_sender, _aid=aid):
            self._on_test_account(_aid)

        item.add(None)
        item.add(rumps.MenuItem("Test login", callback=_test))
        return item

    # ── Scheduler submenu ──────────────────────────────────────────

    def _render_scheduler_submenu(self) -> None:
        self._build_scheduler_submenu(
            enabled=bool(self._scheduler_state.get("enabled")),
            current_interval=self._scheduler_state.get("interval_hours"),
        )

    def _build_scheduler_submenu(self, *, enabled: bool, current_interval: int | None) -> None:
        self._reset_submenu(self._scheduler_menu)
        toggle = rumps.MenuItem(
            "Run in the background",
            callback=self._on_toggle_scheduler,
        )
        toggle.state = 1 if enabled else 0
        self._scheduler_menu.add(toggle)
        self._scheduler_menu.add(None)

        # Interval picker: each item is a checkable choice. Clicking
        # (re)starts the agent at the chosen interval.
        active = current_interval if enabled else None
        for hours in SCHEDULE_INTERVAL_CHOICES:
            label = _interval_label(hours)
            item = rumps.MenuItem(
                label, callback=self._make_interval_callback(hours),
            )
            item.state = 1 if active == hours else 0
            self._scheduler_menu.add(item)

    def _make_interval_callback(self, hours: int):
        def _cb(_sender):
            threading.Thread(
                target=self._set_scheduler,
                args=(True, hours),
                daemon=True,
            ).start()
        return _cb

