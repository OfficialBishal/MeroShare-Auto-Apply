class MeroShareMenuBar(rumps.App):
    def __init__(self) -> None:
        # Icon-only menu bar in steady state: no "MS" or any acronym
        # next to the logo. During the brief cold-start window though,
        # we DO show "Starting…" text next to the icon so the user has
        # immediate visible feedback that double-clicking the .app
        # actually did something. `_auto_start_flask` clears the
        # title once Flask is reachable, returning to icon-only.
        # If the icon PNG is missing (broken install), rumps falls
        # back to the `name` as text — better than a blank slot the
        # user can't click on.
        icon_path = str(ICON_PATH) if ICON_PATH.exists() else None
        super().__init__(
            name="MeroShare",
            title=None if icon_path else "MeroShare",  # icon-only when icon present
            icon=icon_path,
            template=True,  # auto-invert for light/dark menu bars
            # Single "Quit" item (replaces the previous two-button
            # "Quit menu bar" + "Stop everything"). User mental model:
            # Quit = no menu bar = no app running. The handler stops
            # the scheduler, stops Flask, then exits the menubar
            # process — exactly the cleanup the previous "Stop
            # everything" did. We override quit_button=None because
            # we wire our own item below.
            quit_button=None,
        )

        # Long-lived state pulled from the API on each tick. Held on
        # self so submenu builders can read coherent snapshots without
        # re-fetching mid-render.
        self._scheduler_state: dict[str, Any] = {}
        self._issues_state: list[dict[str, Any]] = []
        self._accounts_state: list[dict[str, Any]] = []
        self._config_state: dict[str, Any] = {}
        self._update_info: dict[str, Any] | None = None

        # Spawned Flask process, when we started one. Used by "Stop
        # everything" to terminate the right tree.
        self._flask_proc: subprocess.Popen | None = None

        # NSApp doesn't exist until rumps.App.run() spins up the Cocoa
        # runloop, so anything that pokes NSApp (setActivationPolicy_,
        # setApplicationIconImage_) has to wait. We schedule the
        # application of these post-launch via a one-shot Timer that
        # fires once the runloop is alive. The previous form ran
        # _set_dock_visibility / _refresh_app_icon_image directly in
        # __init__ and silently swallowed an AttributeError on every
        # launch — both became no-ops, so Show-in-Dock didn't apply
        # and the notification icon cache never got refreshed.
        def _post_launch(_sender):
            self._post_launch_timer.stop()
            if _show_in_dock_enabled():
                _set_dock_visibility(True)
            self._refresh_app_icon_image()
        self._post_launch_timer = rumps.Timer(_post_launch, 0.1)
        self._post_launch_timer.start()

        # Build the menu structure once. Most items are stable; the
        # submenu contents get rebuilt by tick handlers as state
        # changes.
        self._build_menu()

        # Refresh + update timers. rumps.Timer fires on the main
        # thread, so each handler offloads HTTP to a background
        # thread to keep the menu responsive.
        self._refresh_timer = rumps.Timer(self._tick, STATUS_REFRESH_INTERVAL_S)
        self._refresh_timer.start()

        self._update_timer = rumps.Timer(
            self._update_tick, UPDATE_CHECK_INTERVAL_S,
        )
        self._update_timer.start()

        # Initial paint without waiting for the 30s tick.
        threading.Thread(target=self._refresh_all, daemon=True).start()
        threading.Timer(
            INITIAL_UPDATE_DELAY_S,
            lambda: threading.Thread(target=self._check_updates, daemon=True).start(),
        ).start()

        # Auto-start Flask on launch. Users mental-model is "open the
        # app → the app is running" — discovering they have to click
        # Open Dashboard to actually start anything was a real
        # user-reported confusion. We spawn it in the background so
        # the menu bar paints immediately while Flask cold-starts;
        # status header switches from "starting…" → "ready" once
        # /api/health responds.
        threading.Thread(target=self._auto_start_flask, daemon=True).start()

        # Notification drain. The Flask process can't fire notifications
        # with the .app's icon (it's detached from the bundle), so it
        # appends to a queue file and we — running inside the .app —
        # drain it and fire rumps.notification, which uses
        # NSUserNotification with the bundle's icon. 1.5s feels
        # immediate to the user without burning cycles.
        self._notify_drain_timer = rumps.Timer(self._drain_notifications, 1.5)
        self._notify_drain_timer.start()

        # Fast sentinel poll. The dashboard's "Stop everything" button
        # writes a sentinel file AND tries to SIGTERM us via pgrep —
        # but Python signal handlers are deferred until the VM yields,
        # and the rumps event loop spends most of its time in a Cocoa
        # runloop call where bytecode isn't running. The signal
        # handler can sit pending for tens of seconds, leaving the
        # menu bar visibly lingering after the user clicked Quit. A
        # rumps.Timer DOES fire on the runloop directly (via NSTimer),
        # so a 1-second sentinel check guarantees teardown within ~1s
        # regardless of signal-handler timing.
        self._sentinel_fast_timer = rumps.Timer(self._sentinel_check_tick, 1.0)
        self._sentinel_fast_timer.start()

        # NB: NSApp.setApplicationIconImage_ now runs from
        # _post_launch_timer above, after the Cocoa runloop is alive.
        # Calling it directly in __init__ (NSApp is None pre-run)
        # silently no-op'd on every launch.

        # SIGTERM handler: when the user clicks Settings → "Stop
        # everything" in the dashboard, /api/shutdown sends us SIGTERM
        # so the menu bar dies in lockstep with Flask. Without this,
        # the status item lingers up to 30 seconds (one sentinel tick).
        # Flask has already done the heavy cleanup (scheduler stop, its
        # own exit), so all we need to do here is release the
        # NSStatusItem and quit. We dispatch the actual quit on a
        # short-delay timer so signal handlers don't fight with the
        # rumps event loop directly.
        def _on_sigterm(_signum, _frame):
            logger.info("Received SIGTERM; shutting down menu bar.")
            # rumps.Timer fires on the main thread which is the safe
            # place to invoke quit_application. A bare 0.05s delay
            # gives the signal handler a chance to return cleanly.
            timer = {"t": None}

            def _fire(_sender):
                if timer["t"]:
                    timer["t"].stop()
                # Best-effort cleanup of the sentinel and any Flask
                # subprocess we spawned. Then exit. Mirrors what the
                # menu bar's "Quit" item does, minus the duplicate
                # /api/shutdown call (Flask is already shutting down
                # — that's WHY it sent us SIGTERM).
                try:
                    SHUTDOWN_SENTINEL.unlink(missing_ok=True)
                except OSError:
                    pass
                if self._flask_proc and self._flask_proc.poll() is None:
                    try:
                        self._flask_proc.terminate()
                    except OSError:
                        pass
                rumps.quit_application()

            timer["t"] = rumps.Timer(_fire, 0.05)
            timer["t"].start()

        try:
            import signal as _signal
            _signal.signal(_signal.SIGTERM, _on_sigterm)
        except (ValueError, OSError) as e:
            # Some embedded contexts (e.g. CI test harness) can't set
            # signal handlers. Fall through to the sentinel-tick path.
            logger.debug("Could not install SIGTERM handler: %s", e)

    # ── Menu construction ──────────────────────────────────────────

