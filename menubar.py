# NSApplicationActivationPolicy values, mirrored here so we don't
# have to import the AppKit constants at module load time (PyObjC
# imports are not free).
_NS_ACTIVATION_POLICY_REGULAR = 0    # Dock icon + Cmd-Tab + menu bar
_NS_ACTIVATION_POLICY_ACCESSORY = 1  # menu bar only (no Dock)


def _set_dock_visibility(visible: bool) -> None:
    """Toggle the Dock icon at runtime via NSApp.setActivationPolicy_.

    macOS lets a running app move between policies without a relaunch,
    so the Show-in-Dock toggle takes effect immediately. Setting
    .regular adds the Dock icon and a Cmd-Tab entry; .accessory hides
    them. The status item stays put either way.
    """
    try:
        from AppKit import NSApp
        policy = (
            _NS_ACTIVATION_POLICY_REGULAR if visible
            else _NS_ACTIVATION_POLICY_ACCESSORY
        )
        NSApp.setActivationPolicy_(policy)
    except Exception as e:
        logger.warning("Could not change activation policy: %s", e)


def _show_in_dock_enabled() -> bool:
    return SHOW_IN_DOCK_MARKER.exists()


def _show_in_dock_set(enabled: bool) -> None:
    """Persist the Dock-visibility preference and apply it now."""
    if enabled:
        SHOW_IN_DOCK_MARKER.parent.mkdir(parents=True, exist_ok=True)
        SHOW_IN_DOCK_MARKER.touch()
    else:
        try:
            SHOW_IN_DOCK_MARKER.unlink(missing_ok=True)
        except OSError as e:
            logger.debug("Could not remove dock marker: %s", e)
    _set_dock_visibility(enabled)


def _activate_foreground() -> None:
    """Pull the menu bar app to the foreground so modal dialogs are visible.

    macOS apps with LSUIElement=true (no Dock icon, just a menu bar
    item) routinely lose foreground state. NSAlert.runModal will
    happily display behind whatever window has focus, leaving the
    user staring at a frozen-looking menu bar. Calling
    activateIgnoringOtherApps_ right before the alert reliably brings
    the alert to the front. rumps.alert tries this internally but
    the timing races with menu dismissal, so we activate explicitly.
    """
    try:
        from AppKit import NSApp
        NSApp.activateIgnoringOtherApps_(True)
    except Exception as e:
        logger.debug("NSApp activation failed: %s", e)


def _osascript_dialog(title: str, message: str) -> None:
    """Last-resort dialog via osascript when rumps.alert silently fails.

    AppleScript dialogs are routed through the system event loop, so
    they bypass any quirks of our LSUIElement-true app. Slower to
    spawn (forks osascript) but always shows up.
    """
    # The escape sequence dance: AppleScript's display-dialog string
    # literal interprets `\n` as a newline and `\\` as a single
    # backslash. To pass a real newline through, the SHELL command
    # line must contain `\n` (two chars). _esc converts Python's real
    # newline char ('\n', U+000A) into the two-char `\\n` sequence
    # that AppleScript turns back into a newline.
    def _esc(s: str) -> str:
        return (
            s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\r", " ").replace("\n", "\\n")
        )
    # Use a REAL newline between title and message — _esc will then
    # produce the AppleScript escape sequence. The previous code
    # used `\\n\\n` (Python literal backslash-n) which got escaped
    # AGAIN by _esc into `\\\\n\\\\n` and showed up verbatim.
    body = f"{title}\n\n{message}" if title else message
    subprocess.run(
        ["osascript", "-e",
         f'display dialog "{_esc(body)}" buttons {{"OK"}} default button 1'],
        check=False, capture_output=True,
    )


def _show_dialog(title: str, message: str) -> None:
    """Display a modal dialog from the menu bar context.

    On macOS with LSUIElement=true (no Dock icon — our default), NSAlert
    routinely renders BEHIND the foreground app and the menu bar
    appears frozen because the alert is blocking the main run loop
    invisibly. `_activate_foreground` mitigates but doesn't always
    win the race against menu dismissal. Symptom: user clicks About,
    sees nothing, can't click anything else.

    Fix: prefer the osascript path on macOS — it routes through the
    system event loop, so it always renders on top. ~50ms slower
    (subprocess fork) but reliable. rumps.alert remains the fallback
    for the non-darwin case and as a last resort if osascript itself
    fails.

    When called from a background thread, dispatches back to the main
    thread because both AppKit and rumps wrap APIs that aren't thread-
    safe.
    """
    if threading.current_thread() is not threading.main_thread():
        # rumps.Timer fires on the main thread. A 0-delay one-shot is
        # the simplest "dispatch back to main" mechanism we have
        # without pulling in PyObjC's NSObject.performSelectorOnMainThread.
        timer = {"t": None}

        def _fire(_sender):
            if timer["t"]:
                timer["t"].stop()
            _show_dialog(title, message)

        timer["t"] = rumps.Timer(_fire, 0.01)
        timer["t"].start()
        return

    _activate_foreground()
    if sys.platform == "darwin":
        try:
            _osascript_dialog(title, message)
            return
        except Exception as e:
            logger.warning(
                "osascript dialog failed (%s); falling back to rumps.alert", e,
            )
    try:
        rumps.alert(title=title, message=message)
    except Exception as e:
        logger.warning("rumps.alert failed (%s)", e)


def _patch_rumps_notification() -> None:
    """Replace `rumps.notification` with an osascript-backed version.

    Module-level monkey-patch because notification calls are scattered
    across menubar.py and changing every call site is churn for a
    behavior change that's the same everywhere — fall back to
    osascript instead of trusting rumps's bundle lookup. Keeps the
    rumps API surface (title/subtitle/message/sound kwargs) so the
    rest of the file reads naturally.
    """
    def _patched(title="", subtitle="", message="", sound=False, **_):
        _native_notification(title=title, message=message, subtitle=subtitle)
    rumps.notification = _patched


def _native_notification(title: str, message: str = "", subtitle: str = "") -> None:
    """Fire a desktop notification via osascript.

    `rumps.notification` reads `CFBundleIdentifier` from
    `NSBundle.mainBundle()`, which for our exec-into-bundled-Python
    layout resolves to the bundled interpreter's `bin/` directory
    rather than the .app — rumps then raises and kills the calling
    thread on every fire. osascript routes notifications through the
    system event loop and doesn't care which binary's bundle is
    "main", so it Just Works for any process layout.

    The previous workaround (writing a stub Info.plist next to the
    bundled Python) confused `codesign --deep` — it treated the
    `bin/` directory as a sub-bundle to sign, which produced an
    invalid manifest that macOS Launch Services rejected at .app
    launch time. Removing the Info.plist plus this osascript path
    sidesteps both bugs.
    """
    def _esc(s: str) -> str:
        return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")
    cmd = f'display notification "{_esc(message)}" with title "{_esc(title)}"'
    if subtitle:
        cmd += f' subtitle "{_esc(subtitle)}"'
    try:
        subprocess.run(
            ["osascript", "-e", cmd],
            check=False, capture_output=True, timeout=5,
        )
    except Exception as e:
        logger.debug("osascript notification failed: %s", e)


def _format_relative(iso_str: str | None) -> str:
    """Render an ISO timestamp as 'Xm ago' / 'in Xh' / etc.

    Naive inputs are interpreted as Asia/Kathmandu (UTC+05:45) to
    match `auto_apply._normalize_applied_date`. Without this, a
    daemon on a non-NPT host reading naive scheduler timestamps
    would display "5h ago" off by the local TZ offset.
    """
    if not iso_str:
        return "unknown"
    try:
        from datetime import datetime, timezone, timedelta
        dt = datetime.fromisoformat(iso_str.replace(" ", "T"))
        if dt.tzinfo is None:
            # Match _normalize_applied_date's Asia/Kathmandu default.
            dt = dt.replace(tzinfo=timezone(timedelta(hours=5, minutes=45)))
        t = dt.timestamp()
    except (ValueError, TypeError):
        return iso_str
    delta = time.time() - t
    past = delta >= 0
    delta = abs(delta)
    if delta < 60:
        return "just now" if past else "in <1m"
    mins = int(delta // 60)
    if mins < 60:
        return f"{mins}m ago" if past else f"in {mins}m"
    hrs = int(mins // 60)
    if hrs < 24:
        return f"{hrs}h ago" if past else f"in {hrs}h"
    days = int(hrs // 24)
    return f"{days}d ago" if past else f"in {days}d"


def _format_amount(npr: int | float | None) -> str:
    if npr is None or npr == "" or npr == 0:
        return "no cap"
    try:
        return f"Rs. {int(npr):,}"
    except (TypeError, ValueError):
        return str(npr)


def _interval_label(hours: int) -> str:
    if hours == 1:
        return "Every hour"
    return f"Every {hours} hours"


